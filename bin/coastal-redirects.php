<?php
declare(strict_types=1);

/**
 * Erzeugt für den Coastal-Umzug (Apache/LiteSpeed) aus dem Export:
 *   php bin/coastal-redirects.php <export.json> <neue-basis-url> [insights-index.json]
 * z. B. php bin/coastal-redirects.php export.json https://insights.coastalcopy.com insights-index.json
 *
 * stdout: 301-Regeln für /insights/<slug>.html, /insights/ und den Feed (in die .htaccess des alten Hostings einfügen).
 * Dritter Parameter (optional): schreibt eine neue insights/index.json für die Seite Coastal-Insights.html. Alte Artikel-Links
 * dort sind Hash-Links (Coastal-Insights.html#<legacy-slug>), die der Server nie sieht; die Seite leitet sie über diese Datei
 * auf die neue Adresse um, und die Karten der Seite zeigen auf die neuen URLs. Die Datei ersetzt insights/index.json auf dem alten Hosting.
 * Es werden nur veröffentlichte Beiträge berücksichtigt.
 */
[$script, $file, $base, $indexOut] = $argv + [null, null, null, null];
$bundle = $file && is_file($file) ? json_decode((string) file_get_contents($file), true) : null;
$base = rtrim((string) $base, '/');
if (!is_array($bundle) || !preg_match('#^https://[a-z0-9.-]+(/[A-Za-z0-9._~/-]*)?$#i', $base)) {
    fwrite(STDERR, "Nutzung: php bin/coastal-redirects.php <export.json> <https://neue-basis-url> [insights-index.json]\n");
    exit(1);
}
$origin = rtrim((string) ($bundle['origin'] ?? 'https://www.coastalcopy.com'), '/');
$out = ["  # insights:begin (generated by bin/coastal-redirects.php)"];
$index = [];
$posts = array_filter((array) ($bundle['posts'] ?? []), static fn ($p) => ($p['status'] ?? '') === 'published' && preg_match('/^[a-z0-9][a-z0-9-]*$/i', (string) ($p['slug'] ?? '')) === 1);
usort($posts, static fn ($a, $b) => strcmp((string) ($b['published_at'] ?? $b['created_at'] ?? ''), (string) ($a['published_at'] ?? $a['created_at'] ?? '')));
foreach ($posts as $p) {
    $slug = (string) $p['slug'];
    $out[] = '  RewriteRule ^insights/' . preg_quote($slug, '/') . '(\.html)?/?$ ' . $base . '/' . $slug . '? [R=301,L,NC]';
    $cover = trim((string) ($p['cover_image'] ?? ''));
    $ts = strtotime((string) ($p['published_at'] ?? $p['created_at'] ?? '')) ?: time();
    $index[] = [
        'slug' => $slug, 'legacy' => $p['legacy_slug'] ?? null, 'url' => $base . '/' . $slug,
        'title' => (string) $p['title'], 'excerpt' => (string) ($p['excerpt'] ?? ''), 'category' => (string) ($p['category'] ?? ''),
        'date' => gmdate('M j, Y', $ts), 'minutes' => max(1, (int) ($p['read_minutes'] ?? 4)),
        'image' => $cover === '' ? '' : (preg_match('#^https?://#i', $cover) ? $cover : $origin . '/' . ltrim($cover, '/')), 'alt' => (string) ($p['cover_alt'] ?? ''),
    ];
}
$out[] = '  RewriteRule ^insights/feed\.xml$ ' . $base . '/feed.xml? [R=301,L,NC]';
$out[] = '  RewriteRule ^insights/?$ ' . $base . '/? [R=301,L,NC]';
$out[] = '  # insights:end';
echo implode("\n", $out), "\n";
if ($indexOut) {
    if (@file_put_contents($indexOut, json_encode($index, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR)) === false) {
        fwrite(STDERR, "Index-Datei konnte nicht geschrieben werden: $indexOut\n");
        exit(1);
    }
}
