<?php
declare(strict_types=1);

/**
 * Erzeugt die 301-Weiterleitungen für den Coastal-Umzug (Apache/LiteSpeed) aus dem Export:
 *   php bin/coastal-redirects.php <export.json> <neue-basis-url>
 * z. B. php bin/coastal-redirects.php export.json https://insights.coastalcopy.com
 * Ausgabe (stdout) in site/.htaccess des alten Hostings einfügen. Es werden nur veröffentlichte Beiträge berücksichtigt;
 * /insights/ selbst und der Feed zeigen auf die Startseite bzw. den Feed der neuen Adresse.
 */
[$script, $file, $base] = $argv + [null, null, null];
$bundle = $file && is_file($file) ? json_decode((string) file_get_contents($file), true) : null;
$base = rtrim((string) $base, '/');
if (!is_array($bundle) || !preg_match('#^https://[a-z0-9.-]+(/[A-Za-z0-9._~/-]*)?$#i', $base)) {
    fwrite(STDERR, "Nutzung: php bin/coastal-redirects.php <export.json> <https://neue-basis-url>\n");
    exit(1);
}
$out = ["  # insights:begin (generated by bin/coastal-redirects.php)"];
foreach ((array) ($bundle['posts'] ?? []) as $p) {
    $slug = (string) ($p['slug'] ?? '');
    if (($p['status'] ?? '') !== 'published' || preg_match('/^[a-z0-9][a-z0-9-]*$/i', $slug) !== 1) {
        continue;
    }
    $out[] = '  RewriteRule ^insights/' . preg_quote($slug, '/') . '(\.html)?/?$ ' . $base . '/' . $slug . '? [R=301,L,NC]';
}
$out[] = '  RewriteRule ^insights/feed\.xml$ ' . $base . '/feed.xml? [R=301,L,NC]';
$out[] = '  RewriteRule ^insights/?$ ' . $base . '/? [R=301,L,NC]';
$out[] = '  # insights:end';
echo implode("\n", $out), "\n";
